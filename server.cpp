using Buffer = std::vector<uint8_t>;

struct Connection {
  Fd fd{};

  // application's intention, for the event loop
  bool wantsToRead{false};
  bool wantsToWrite{false};
  bool wantsToClose{false};

  // buffered input and output
  std::vector<uint8_t> incoming{}; // data to be parsed by the application
  std::vector<uint8_t> outgoing{}; // responses generated by the application

  // timer
  std::uint64_t lastActiveMs{};
  DList idleNode{};
};
static struct {
  HashMap map{};
  // a map of all client connections, keyed by fd
  std::vector<std::unique_ptr<Connection>> connections;

  // timers for idle connections
  DList idleList{};
  // timer for TTL
  Heap _heap{};
  // thread pool
  ThreadPool threadPool{numThreads};

} gData; // top-level hashtable
// Response::status
enum class ResponseStatus : uint32_t {
  Ok = 0,
  Err = 1,      // error
  NotFound = 2, // key not found
};
// KV pair for the top-level hashtable
struct Entry {

  Entry(){};
  Entry(Types other) { type = other; }
  ~Entry() { setTTL(this, -1); }
  struct HashNode node {};
  size_t heapIdx{NotInHeap};
  std::string key{};
  Types type{};
  std::string str{};
  ZSet zSet{};
};
struct LookupKey {
  HashNode node{};
  std::string key{};
};
auto setNonBlocking(const int fd) -> void {

  errno = 0;
  int flags = fcntl(fd, F_GETFL, 0);
  if (errno) {
    die("fcntl error");
    return;
  }

  flags |= O_NONBLOCK;

  errno = 0;
  static_cast<void>(fcntl(fd, F_SETFL, flags));
  if (errno)
    die("fcntl error");
}
auto handleAccept(const int fd) -> void {

  // accept
  struct sockaddr_in clientAddr {};
  socklen_t addrLen = sizeof(clientAddr);
  int clientSocket = accept(fd, reinterpret_cast<sockaddr *>(&clientAddr), &addrLen);
  if (clientSocket < 0) {
    msgErrno("accept() error");
    return;
  }

  uint32_t ip = clientAddr.sin_addr.s_addr;
  std::cerr << "new client from " << (ip & 255) << '.' << ((ip >> 8) & 255) << '.'
            << ((ip >> 16) & 255) << '.' << (ip >> 24) << ':' << ntohs(clientAddr.sin_port) << '\n';

  // set the new connection fd to nonblocking mode
  setNonBlocking(clientSocket);

  // create a `struct Conn`
  auto connection = std::make_unique<Connection>();
  connection->fd = Fd(clientSocket);
  connection->wantsToRead = true;
  connection->lastActiveMs = getMonotonicMilliseconds();
  gData.idleList.insertBefore(&connection->idleNode);

  // put it into the map
  if (gData.connections.size() <= static_cast<size_t>(connection->fd.get()))
    gData.connections.resize(connection->fd.get() + 1);

  assert(!gData.connections[connection->fd.get()]);
  gData.connections[connection->fd.get()] = std::move(connection);
}
auto tryReadUint32(const uint8_t *&current, const uint8_t *end, uint32_t &out) -> bool {

  if (current + 4 > end)
    return false;

  std::memcpy(&out, current, 4);
  current += 4;
  return true;
}
auto tryReadString(const uint8_t *&current, const uint8_t *end, const size_t len,
                   std::string &out) -> bool {
  if (current + len > end)
    return false;

  out.assign(current, current + len);
  current += len;
  return true;
}
// +------+-----+------+-----+------+-----+-----+------+
// | nstr | len | str1 | len | str2 | ... | len | strn |
// +------+-----+------+-----+------+-----+-----+------+
auto parseRequest(const uint8_t *data, size_t size, std::vector<std::string> &out) -> int32_t {
  const uint8_t *end = data + size;
  uint32_t nstr{};
  if (!tryReadUint32(data, end, nstr))
    return -1;
  if (nstr > maxArgs)
    return -1; // safety limit

  while (out.size() < nstr) {
    uint32_t len{};
    if (!tryReadUint32(data, end, len))
      return -1;

    out.push_back(std::string());
    if (!tryReadString(data, end, len, out.back()))
      return -1;
  }

  if (data != end)
    return -1; // trailing garbage
  return 0;
}
// help functions for the serialization
template <typename T> auto bufferAppend(Buffer &buffer, T data) -> void {

  static_assert(std::is_arithmetic_v<T> || std::is_enum_v<T>, "buffer needs a number type");

  size_t len = sizeof(T);
  auto addr = reinterpret_cast<const uint8_t *>(&data);
  buffer.insert(buffer.end(), addr, addr + len);
}
// append serialized data types to the back
auto serializeNil(Buffer &out) -> void { bufferAppend(out, Tag::Nil); }
auto serializeString(Buffer &out, std::string_view s) -> void {
  bufferAppend(out, Tag::String);
  bufferAppend(out, static_cast<uint32_t>(s.length()));
  bufferAppendBytes(out, reinterpret_cast<const uint8_t *>(s.data()), s.length());
}
auto serializeInt(Buffer &out, int64_t val) -> void {
  bufferAppend(out, Tag::Int64);
  bufferAppend(out, val);
}
auto serializeDouble(Buffer &out, double val) -> void {
  bufferAppend(out, Tag::Double);
  bufferAppend(out, val);
}
auto serializeError(Buffer &out, TagError code, const std::string &msg) -> void {
  bufferAppend(out, Tag::Error);
  bufferAppend(out, code);
  bufferAppend(out, static_cast<uint32_t>(msg.length()));
  bufferAppendBytes(out, reinterpret_cast<const uint8_t *>(msg.data()), msg.length());
}
auto serializeArray(Buffer &out, uint32_t arraySize) -> void {
  bufferAppend(out, Tag::Array);
  bufferAppend(out, arraySize);
}
auto serializeBeginArray(Buffer &out) -> size_t {
  bufferAppend(out, Tag::Array);
  bufferAppend(out, static_cast<uint32_t>(0)); // filled by out_end_arr()
  return out.size() - 4;                       // the `ctx` arg
}
auto serializeEndArray(Buffer &out, size_t ctx, std::uint32_t n) {
  assert(out[ctx - 1] == static_cast<uint8_t>(Tag::Array));
  std::memcpy(&out[ctx], &n, 4);
}
// equality comparison for `struct Entry`
auto eqEntry(HashNode *lhs, HashNode *rhs) -> bool {
  const auto *entry = containerOf(lhs, Entry, node);
  const auto *lookupKey = containerOf(rhs, LookupKey, node);
  return entry->key == lookupKey->key;
}
auto delEntryFn(void *arg) -> void {
  // std::cerr << "deleting on worker thread " << std::this_thread::get_id() << "\n";
  delete static_cast<Entry *>(arg);
}
auto delEntry(Entry *entry) -> void {
  setTTL(entry, -1);
  size_t setSize = (entry->type == Types::ZSet) ? entry->zSet.getMapSize() : 0;
  const size_t largeContainerSize = 1000;
  if (setSize > largeContainerSize) {
    gData.threadPool.queue(delEntryFn, entry);
  } else {
    delete entry; // small; avoid context switches
  }
}
auto doGet(std::vector<std::string> &cmd, Buffer &out) -> void {

  // a dummy `LookupKey` just for the lookup
  LookupKey key{};
  key.key.swap(cmd[1]);
  key.node.hashCode = stringHash(reinterpret_cast<const uint8_t *>(key.key.data()), key.key.size());

  // hashtable lookup
  HashNode *node = gData.map.lookup(&key.node, &eqEntry);
  if (!node)
    return serializeNil(out);

  // copy the value
  auto entry = containerOf(node, Entry, node);
  if (entry->type != Types::String) {
    return serializeError(out, TagError::BadType, "not a string value");
  }
  return serializeString(out, entry->str);
}
auto doSet(std::vector<std::string> &cmd, Buffer &out) -> void {

  // a dummy `LookupKey` just for the lookup
  LookupKey key{};
  key.key.swap(cmd[1]);
  key.node.hashCode = stringHash(reinterpret_cast<const uint8_t *>(key.key.data()), key.key.size());

  // hashtable lookup
  HashNode *node = gData.map.lookup(&key.node, &eqEntry);
  if (node) {
    // found, update the value
    auto entry = containerOf(node, Entry, node);
    if (entry->type != Types::String) {
      return serializeError(out, TagError::BadType, "a non-string value exists");
    }
    entry->str.swap(cmd[2]);
  } else {
    // not found, allocate & insert a new pair
    auto entry = new Entry(Types::String);
    entry->key.swap(key.key);
    entry->node.hashCode = key.node.hashCode;
    entry->str.swap(cmd[2]);
    gData.map.insert(&entry->node);
  }
  return serializeNil(out);
}
auto doDel(std::vector<std::string> &cmd, Buffer &out) -> void {

  // a dummy `LookupKey` just for the lookup
  LookupKey key{};
  key.key.swap(cmd[1]);
  key.node.hashCode = stringHash(reinterpret_cast<const uint8_t *>(key.key.data()), key.key.size());

  // hashtable delete
  HashNode *node = gData.map.remove(&key.node, &eqEntry);
  if (node) // deallocate the pair
    delEntry(containerOf(node, Entry, node));

  return serializeInt(out, node ? 1 : 0);
}
auto keysCallback(HashNode *node, void *arg) -> bool {
  Buffer &out = *static_cast<Buffer *>(arg);
  const std::string &key = containerOf(node, Entry, node)->key;
  serializeString(out, key);
  return true;
}
auto doKeys(std::vector<std::string> &, Buffer &out) -> void {
  serializeArray(out, static_cast<uint32_t>(gData.map.size()));
  gData.map.forEach(&keysCallback, static_cast<void *>(&out));
}
// zadd zset score name
auto handleZAdd(std::vector<std::string> &cmd, Buffer &out) -> void {

  double score{};
  if (!stringToDouble(cmd[2], score))
    return serializeError(out, TagError::BadArg, "expects float");

  // look up or create the zset
  LookupKey key{};
  key.key.swap(cmd[1]);
  key.node.hashCode = stringHash(reinterpret_cast<uint8_t *>(key.key.data()), key.key.length());
  auto *hashNode = gData.map.lookup(&key.node, &eqEntry);

  Entry *entry{};
  if (!hashNode) // insert a new key
  {
    entry = new Entry(Types::ZSet);
    entry->key.swap(key.key);
    entry->node.hashCode = key.node.hashCode;
    gData.map.insert(&entry->node);
  } else { // check the existing key
    entry = containerOf(hashNode, Entry, node);
    if (entry->type != Types::ZSet)
      return serializeError(out, TagError::BadType, "expect zset");
  }
  // add or update the tuple
  std::string &name{cmd[3]};
  bool added = entry->zSet.insert(name, score);
  return serializeInt(out, added);
}
auto setTTL(Entry *entry, std::int64_t TTLmilliseconds) -> void {

  if (TTLmilliseconds < 0 && entry->heapIdx != NotInHeap) {

    // setting a negative TTL means removing the TTL
    gData._heap.remove(entry->heapIdx);
    entry->heapIdx = NotInHeap;
  } else if (TTLmilliseconds >= 0) {
    // add or update the heap data structure
    std::uint64_t expireAt = getMonotonicMilliseconds() + static_cast<uint64_t>(TTLmilliseconds);
    HeapItem item = {expireAt, &entry->heapIdx};
    gData._heap.upsert(entry->heapIdx, item);
  }
}
// PEXPIRE key ttl_ms
auto expire(std::vector<std::string> &cmd, Buffer &out) {
  std::int64_t TTLmilliseconds{};
  if (!stringToInt(cmd[2], TTLmilliseconds))
    return serializeError(out, TagError::BadArg, "expect int64");

  LookupKey key;
  key.key.swap(cmd[1]);
  key.node.hashCode = stringHash(reinterpret_cast<uint8_t *>(key.key.data()), key.key.size());

  auto *node = gData.map.lookup(&key.node, eqEntry);
  if (node) {
    auto entry = containerOf(node, Entry, node);
    setTTL(entry, TTLmilliseconds);
  }

  return serializeInt(out, node ? 1 : 0);
}
// PTTL key
auto doTTL(std::vector<std::string> &cmd, Buffer &out) -> void {
  LookupKey key;
  key.key.swap(cmd[1]);
  key.node.hashCode = stringHash(reinterpret_cast<uint8_t *>(key.key.data()), key.key.size());

  auto node = gData.map.lookup(&key.node, eqEntry);
  if (!node) {
    return serializeInt(out, -2); // not found
  }

  auto *entry = containerOf(node, Entry, node);
  if (entry->heapIdx == NotInHeap) {
    return serializeInt(out, -1); // no TTL
  }

  std::uint64_t expireAt = gData._heap[entry->heapIdx].val;
  std::uint64_t currentMilliseconds = getMonotonicMilliseconds();
  return serializeInt(out, expireAt > currentMilliseconds ? (expireAt - currentMilliseconds) : 0);
}
auto lookupZSet(std::string &s) -> ZSet * {
  LookupKey key{};
  key.key.swap(s);
  key.node.hashCode = stringHash(reinterpret_cast<uint8_t *>(key.key.data()), key.key.length());
  auto *hashNode = gData.map.lookup(&key.node, eqEntry);

  if (!hashNode) // a non-existent key is treated as an empty zset
    return &emptyZSet;

  auto *entry = containerOf(hashNode, Entry, node);
  return entry->type == Types::ZSet ? &entry->zSet : nullptr;
}
// zrem zset name
auto handleZRem(std::vector<std::string> &cmd, Buffer &out) -> void {
  auto zSet = lookupZSet(cmd[1]);
  if (!zSet)
    return serializeError(out, TagError::BadType, "expect zset");

  std::string &name = cmd[2];
  auto *zNode = zSet->lookup(name);
  if (zNode)
    zSet->remove(zNode);

  return serializeInt(out, zNode ? 1 : 0);
}
// zscore zset name
auto handleZScore(std::vector<std::string> &cmd, Buffer &out) -> void {
  auto zSet = lookupZSet(cmd[1]);
  if (!zSet)
    return serializeError(out, TagError::BadType, "expect zset");

  std::string &name = cmd[2];
  auto zNode = zSet->lookup(name);
  return zNode ? serializeDouble(out, zNode->score) : serializeNil(out);
}
// zquery zset score name offset limit
auto handleZQuery(std::vector<std::string> &cmd, Buffer &out) -> void {
  // prase args
  double score{};
  if (!stringToDouble(cmd[2], score))
    return serializeError(out, TagError::BadArg, "expect fp number");

  std::string &name = cmd[3];
  std::int64_t offset{};
  std::int64_t limit{};
  if (!stringToInt(cmd[4], offset) || !stringToInt(cmd[5], limit))
    return serializeError(out, TagError::BadArg, "expect int");

  // get the zset
  auto zSet = lookupZSet(cmd[1]);
  if (!zSet)
    return serializeError(out, TagError::BadType, "expect zset");

  auto zNode = zSet->seekGreaterOrEqual(name, score);
  zNode = zSet->offset(zNode, offset);

  // output
  size_t ctx = serializeBeginArray(out);
  std::int64_t n{};
  while (zNode && n < limit) {
    serializeString(out, zNode->name);
    serializeDouble(out, zNode->score);
    zNode = zSet->offset(zNode, +1);
    n += 2;
  }
  serializeEndArray(out, ctx, static_cast<std::uint32_t>(n));
}
auto doRequest(std::vector<std::string> &cmd, Buffer &out) -> void {

  if (cmd.size() == 2 && cmd[0] == "get")
    return doGet(cmd, out);
  else if (cmd.size() == 3 && cmd[0] == "set")
    return doSet(cmd, out);
  else if (cmd.size() == 2 && cmd[0] == "del")
    return doDel(cmd, out);
  else if (cmd.size() == 3 && cmd[0] == "pexpire")
    return expire(cmd, out);
  else if (cmd.size() == 2 && cmd[0] == "pttl")
    return doTTL(cmd, out);
  else if (cmd.size() == 1 && cmd[0] == "keys")
    return doKeys(cmd, out);
  else if (cmd.size() == 4 && cmd[0] == "zadd")
    return handleZAdd(cmd, out);
  else if (cmd.size() == 3 && cmd[0] == "zrem")
    return handleZRem(cmd, out);
  else if (cmd.size() == 3 && cmd[0] == "zscore")
    return handleZScore(cmd, out);
  else if (cmd.size() == 6 && cmd[0] == "zquery")
    return handleZQuery(cmd, out);
  else
    return serializeError(out, TagError::Unknown, "unknown command");
}
auto beginResponse(Buffer &out, size_t *header) -> void {
  *header = out.size();                        // messege header position
  bufferAppend(out, static_cast<uint32_t>(0)); // reserve space
}
auto getResponseSize(Buffer &out, size_t header) -> size_t { return out.size() - header - 4; }
auto endResponse(Buffer &out, size_t header) -> void {

  auto msgSize = getResponseSize(out, header);

  if (msgSize > maxMsg) {
    out.resize(header + 4);
    serializeError(out, TagError::TooBig, "response is too big.");
    msgSize = getResponseSize(out, header);
  }

  // message header
  auto len = static_cast<uint32_t>(msgSize);
  std::memcpy(&out[header], &len, 4);
}
// process 1 request if there is enough data
auto tryOneRequest(Connection &connection) -> bool {

  // try to parse the protocol: message header
  if (connection.incoming.size() < 4)
    return false; // wants to read

  uint32_t len{};
  std::memcpy(&len, connection.incoming.data(), 4);
  if (len > maxMsg) {
    msg("too long");
    connection.wantsToClose = true;
    return false; // wants to close
  }

  // message body
  if (4 + len > connection.incoming.size())
    return false; // want to read

  const uint8_t *request = &connection.incoming[4];

  // got one request, do some application logic
  std::vector<std::string> cmd{};
  if (parseRequest(request, len, cmd) < 0) {
    msg("bad request");
    connection.wantsToClose = true;
    return false; // want to close
  }

  size_t headerPos{};
  beginResponse(connection.outgoing, &headerPos);
  doRequest(cmd, connection.outgoing);
  endResponse(connection.outgoing, headerPos);

  // application logic done! remove the request message.
  consumeBuffer(connection.incoming, 4 + len);
  return true; // success
}
// application callback when the socket is writable
auto handleWrite(Connection &connection) -> void {

  assert(connection.outgoing.size() > 0);

  ssize_t returnVal =
      write(connection.fd.get(), connection.outgoing.data(), connection.outgoing.size());

  if (returnVal < 0 && errno == EAGAIN)
    return; // actually not ready
  if (returnVal < 0) {
    msgErrno("write() error");
    connection.wantsToClose = true; // error handling
    return;
  }

  // remove written data from `outgoing`
  consumeBuffer(connection.outgoing, static_cast<size_t>(returnVal));

  // update the readiness intention
  if (connection.outgoing.size() == 0) { // all data written
    connection.wantsToRead = true;
    connection.wantsToWrite = false;
  } // else: want write
}
// application callback when the socket is readable
auto handleRead(Connection &connection) -> void {

  // read some data
  uint8_t buffer[64 * 1024];
  ssize_t returnVal = read(connection.fd.get(), buffer, sizeof(buffer));
  if (returnVal < 0 && errno == EAGAIN)
    return; // actually not ready;
  if (returnVal < 0) {
    // handle IO error
    msgErrno("read() error");
    connection.wantsToClose = true;
    return;
  }
  if (returnVal == 0) {
    // handle EOF
    if (connection.incoming.size() == 0)
      msg("client closed");
    else
      msg("unexpected EOF");

    connection.wantsToClose = true;
    return;
  }

  // got some new data
  bufferAppendBytes(connection.incoming, buffer, static_cast<size_t>(returnVal));

  // parse requests and generate responses
  while (tryOneRequest(connection)) {
  }

  // update the readiness intention
  if (connection.outgoing.size() > 0) { // has a response
    connection.wantsToRead = false;
    connection.wantsToWrite = true;
    // The socket is likely ready to write in a request-response protocol,
    // try to write it without waiting for the next iteration.
    return handleWrite(connection);
  } // else: want read
}
auto nextTimerMilliseconds() -> std::int32_t {

  std::uint64_t currentMilliseconds = getMonotonicMilliseconds();
  std::uint64_t nextMilliseconds = NotInHeap;

  // idle timers using a linked lis
  if (!gData.idleList.isEmpty()) {
    auto connection = containerOf(gData.idleList.getNext(), Connection, idleNode);
    nextMilliseconds = connection->lastActiveMs + idleTimeoutMilliseconds;
  }

  // TTL timers using a heap
  if (!gData._heap.empty() && gData._heap[0].val < nextMilliseconds)
    nextMilliseconds = gData._heap[0].val;

  if (nextMilliseconds == NotInHeap)
    return -1; // no timers, no timeouts

  if (nextMilliseconds <= currentMilliseconds)
    return 0; // missed?

  return static_cast<int32_t>(nextMilliseconds - currentMilliseconds);
}
auto sameNode(HashNode *node, HashNode *key) -> bool { return node == key; }
auto processTimers() -> void {

  auto currentMilliseconds = getMonotonicMilliseconds();
  while (!gData.idleList.isEmpty()) {
    auto connection = containerOf(gData.idleList.getNext(), Connection, idleNode);
    std::uint64_t nextMilliseconds = connection->lastActiveMs + idleTimeoutMilliseconds;
    if (nextMilliseconds >= currentMilliseconds)
      break; // not expired

    std::cerr << "removing idle connection: " << connection->fd.get() << "\n";
    gData.connections[connection->fd.get()] = nullptr;
  }

  // TTL timers using a heap

  const size_t maxWorks = 2000;
  size_t nworks{};

  while (!gData._heap.empty() && gData._heap[0].val < currentMilliseconds) {
    auto entry = containerOf(gData._heap[0].ref, Entry, heapIdx);
    auto node = gData.map.remove(&entry->node, sameNode);
    assert(node == &entry->node);

    // fprintf(stderr, "key expired: %s\n", ent->key.c_str());
    // delete the key
    delete entry;
    if (nworks++ >= maxWorks) // don't stall the server if too many keys are expiring at once
      break;
  }
}
/** Server setup
 * * socket() asks the kernel for a TCP socket and gets a file descriptor
 * back.
 * * setsockopt(SO_REUSEADDR) lets you restart the server right away on the
 * same
 * * port.
 * * bind() attaches the socket to port 1234 on every local address (0.0.0.0).
 * * listen() turns it into a listening socket. From here the kernel accepts
 * * connections on its behalf and queues them.
 * * accept() blocks until a client is in
 * * the queue.
 *   @param Fd
 */
int main() {
  // AF_INET => IPv4 , AF_INET6 => IPv6
  // SOCK_STREAM => TCP, SOCK_DGRAP => UDP
  Fd fd(socket(AF_INET, SOCK_STREAM, 0));
  if (fd.get() < 0)
    die("socket()");

  // this is needed for most server applications
  int val = 1;
  setsockopt(fd.get(), SOL_SOCKET, SO_REUSEADDR, &val, sizeof(val));

  /*
  struct sockaddr_in {
  sa_family_t    sin_family; address family: AF_INET
  in_port_t sin_port;       port in network byte order
  struct in_addr sin_addr;  internet address
}; */

  // bind
  sockaddr_in address{}; // sockaddr_in holds IPv4 port pair
  address.sin_family = AF_INET;
  address.sin_port = htons(1234); // htons => Host To Network short (short = uint16_t)
  address.sin_addr.s_addr = htonl(0);

  int returnVal = bind(fd.get(), reinterpret_cast<const sockaddr *>(&address), sizeof(address));
  if (returnVal)
    die("bind()");

  // set the listen fd to nonblocking mode
  setNonBlocking(fd.get());

  // listen
  returnVal = listen(fd.get(), SOMAXCONN); // SOMAXCONN = 4096
  if (returnVal)
    die("listen()");

  // the event loop
  std::vector<struct pollfd> pollArgs{};

  while (true) {

    // prepare the arguments of the poll()
    pollArgs.clear();

    // put the listening sockets in the first position
    pollfd pfd{fd.get(), POLLIN, 0};
    pollArgs.push_back(pfd);

    // the rest are connection sockets
    for (auto &connection : gData.connections) {
      if (!connection)
        continue;

      // always poll() for error
      pfd = {connection->fd.get(), POLLERR, 0};

      // poll() flags from the application's intent
      if (connection->wantsToRead)
        pfd.events |= POLLIN;
      if (connection->wantsToWrite)
        pfd.events |= POLLOUT;

      pollArgs.push_back(pfd);
    }

    // wait for readiness

    std::int32_t timeoutMilliseconds = nextTimerMilliseconds();
    int returnVal =
        poll(pollArgs.data(), static_cast<nfds_t>(pollArgs.size()), timeoutMilliseconds);
    if (returnVal < 0 && errno == EINTR)
      continue; // not an error
    if (returnVal < 0)
      die("poll");

    // handle the listening socket
    if (pollArgs[0].revents)
      handleAccept(fd.get());

    // handle connection sockets
    for (size_t i = 1; i < pollArgs.size(); ++i) { // skips first pollArgs
      uint32_t ready = pollArgs[i].revents;
      if (ready == 0)
        continue;

      auto &connection = gData.connections[pollArgs[i].fd];

      // update the idle timer by moving conn to the end of the list
      connection->lastActiveMs = getMonotonicMilliseconds();
      connection->idleNode.detach();
      gData.idleList.insertBefore(&connection->idleNode);

      // handle IO
      if (ready & POLLIN) {
        assert(connection->wantsToRead);
        handleRead(*connection); // application logic
      }

      if (ready & POLLOUT) {
        assert(connection->wantsToWrite);
        handleWrite(*connection); // application logic
      }

      // close the socket from socket error or application logic
      if ((ready & POLLERR) || connection->wantsToClose) {
        gData.connections[connection->fd.get()].reset();
      }
    } // for each connection sockets
    // handle timers
    processTimers();
  } // the event loop
}
